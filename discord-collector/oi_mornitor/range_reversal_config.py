"""区间反转信号（射击之星/锤子）环境配置 — 仅告警，不下单。"""
from __future__ import annotations

from typing import Tuple

from oi_mornitor.env_parse import env_bool, env_csv_lower, env_float, env_int, env_str

_ENABLED: bool = True
RANGE_REVERSAL_LOOKBACK_BARS: int = 48
RANGE_REVERSAL_TOUCH_TOL_PCT: float = 0.003
RANGE_REVERSAL_MIN_TOUCHES: int = 2
RANGE_REVERSAL_BREAK_BUFFER_PCT: float = 0.002
RANGE_REVERSAL_EDGE_ZONE_FRAC: float = 0.15
RANGE_REVERSAL_WIDTH_MIN_PCT_MAJOR: float = 0.015
RANGE_REVERSAL_WIDTH_MAX_PCT_MAJOR: float = 0.08
RANGE_REVERSAL_WIDTH_MIN_PCT_ALT: float = 0.03
RANGE_REVERSAL_WIDTH_MAX_PCT_ALT: float = 0.15
RANGE_REVERSAL_SL_BUFFER_PCT: float = 0.001
RANGE_REVERSAL_SL_ATR_MULT: float = 0.15
RANGE_REVERSAL_TP_EDGE_BUFFER_PCT: float = 0.001
RANGE_REVERSAL_VOL_MULT: float = 1.2
RANGE_REVERSAL_KLINE_LIMIT: int = 500
RANGE_REVERSAL_MAJOR_SYMBOLS: Tuple[str, ...] = ("BTCUSDT", "ETHUSDT", "SOLUSDT")
RANGE_REVERSAL_INTERVALS: Tuple[str, ...] = ("15m", "1h", "4h")
RANGE_REVERSAL_BT_MONTHS: int = 6
RANGE_REVERSAL_BT_ALT_MAX: int = 12
RANGE_REVERSAL_SCAN_ALT_MAX: int = 24
RANGE_REVERSAL_TELEGRAM_CHAT_ID: str = ""


def _apply() -> None:
    global _ENABLED
    global RANGE_REVERSAL_LOOKBACK_BARS
    global RANGE_REVERSAL_TOUCH_TOL_PCT
    global RANGE_REVERSAL_MIN_TOUCHES
    global RANGE_REVERSAL_BREAK_BUFFER_PCT
    global RANGE_REVERSAL_EDGE_ZONE_FRAC
    global RANGE_REVERSAL_WIDTH_MIN_PCT_MAJOR
    global RANGE_REVERSAL_WIDTH_MAX_PCT_MAJOR
    global RANGE_REVERSAL_WIDTH_MIN_PCT_ALT
    global RANGE_REVERSAL_WIDTH_MAX_PCT_ALT
    global RANGE_REVERSAL_SL_BUFFER_PCT
    global RANGE_REVERSAL_SL_ATR_MULT
    global RANGE_REVERSAL_TP_EDGE_BUFFER_PCT
    global RANGE_REVERSAL_VOL_MULT
    global RANGE_REVERSAL_KLINE_LIMIT
    global RANGE_REVERSAL_MAJOR_SYMBOLS
    global RANGE_REVERSAL_INTERVALS
    global RANGE_REVERSAL_BT_MONTHS
    global RANGE_REVERSAL_BT_ALT_MAX
    global RANGE_REVERSAL_SCAN_ALT_MAX
    global RANGE_REVERSAL_TELEGRAM_CHAT_ID

    _ENABLED = env_bool("OI_RANGE_REVERSAL_ENABLED", True)
    RANGE_REVERSAL_LOOKBACK_BARS = env_int("OI_RANGE_REVERSAL_LOOKBACK_BARS", 48, min_val=20)
    RANGE_REVERSAL_TOUCH_TOL_PCT = env_float("OI_RANGE_REVERSAL_TOUCH_TOL_PCT", 0.003, min_val=0.0005)
    RANGE_REVERSAL_MIN_TOUCHES = env_int("OI_RANGE_REVERSAL_MIN_TOUCHES", 2, min_val=2)
    RANGE_REVERSAL_BREAK_BUFFER_PCT = env_float("OI_RANGE_REVERSAL_BREAK_BUFFER_PCT", 0.002, min_val=0.0)
    RANGE_REVERSAL_EDGE_ZONE_FRAC = env_float("OI_RANGE_REVERSAL_EDGE_ZONE_FRAC", 0.15, min_val=0.05, max_val=0.4)
    RANGE_REVERSAL_WIDTH_MIN_PCT_MAJOR = env_float("OI_RANGE_REVERSAL_WIDTH_MIN_PCT_MAJOR", 0.015, min_val=0.005)
    RANGE_REVERSAL_WIDTH_MAX_PCT_MAJOR = env_float("OI_RANGE_REVERSAL_WIDTH_MAX_PCT_MAJOR", 0.08, min_val=0.02)
    RANGE_REVERSAL_WIDTH_MIN_PCT_ALT = env_float("OI_RANGE_REVERSAL_WIDTH_MIN_PCT_ALT", 0.03, min_val=0.01)
    RANGE_REVERSAL_WIDTH_MAX_PCT_ALT = env_float("OI_RANGE_REVERSAL_WIDTH_MAX_PCT_ALT", 0.15, min_val=0.04)
    RANGE_REVERSAL_SL_BUFFER_PCT = env_float("OI_RANGE_REVERSAL_SL_BUFFER_PCT", 0.001, min_val=0.0)
    RANGE_REVERSAL_SL_ATR_MULT = env_float("OI_RANGE_REVERSAL_SL_ATR_MULT", 0.15, min_val=0.0)
    RANGE_REVERSAL_TP_EDGE_BUFFER_PCT = env_float("OI_RANGE_REVERSAL_TP_EDGE_BUFFER_PCT", 0.001, min_val=0.0)
    RANGE_REVERSAL_VOL_MULT = env_float("OI_RANGE_REVERSAL_VOL_MULT", 1.2, min_val=1.0)
    RANGE_REVERSAL_KLINE_LIMIT = env_int("OI_RANGE_REVERSAL_KLINE_LIMIT", 500, min_val=200)
    RANGE_REVERSAL_MAJOR_SYMBOLS = tuple(
        s.upper()
        for s in env_csv_lower("OI_RANGE_REVERSAL_MAJOR_SYMBOLS", "btcusdt,ethusdt,solusdt")
    )
    RANGE_REVERSAL_INTERVALS = env_csv_lower("OI_RANGE_REVERSAL_INTERVALS", "15m,1h,4h")
    RANGE_REVERSAL_BT_MONTHS = env_int("OI_RANGE_REVERSAL_BT_MONTHS", 6, min_val=1)
    RANGE_REVERSAL_BT_ALT_MAX = env_int("OI_RANGE_REVERSAL_BT_ALT_MAX", 12, min_val=0)
    RANGE_REVERSAL_SCAN_ALT_MAX = env_int("OI_RANGE_REVERSAL_SCAN_ALT_MAX", 24, min_val=0)

    from oi_mornitor.trendline_config import TRENDLINE_TELEGRAM_CHAT_ID

    chat = env_str("OI_RANGE_REVERSAL_TELEGRAM_CHAT_ID", "")
    RANGE_REVERSAL_TELEGRAM_CHAT_ID = chat.strip() or TRENDLINE_TELEGRAM_CHAT_ID


def is_range_reversal_enabled() -> bool:
    return _ENABLED


def width_pct_bounds(symbol: str) -> tuple[float, float]:
    from oi_mornitor.symbol_aliases import human_base_asset

    base = human_base_asset(symbol) or str(symbol or "").upper()
    if base in ("BTC", "ETH", "SOL"):
        return RANGE_REVERSAL_WIDTH_MIN_PCT_MAJOR, RANGE_REVERSAL_WIDTH_MAX_PCT_MAJOR
    return RANGE_REVERSAL_WIDTH_MIN_PCT_ALT, RANGE_REVERSAL_WIDTH_MAX_PCT_ALT


_apply()
